def _compare_html(term, compare):
    metric, unit = term["metric"], term["unit"]
    lower_better = term["lower_better"]
    rows = ""
    vals = [c["value"] for c in compare if c.get("value") is not None]
    best = (min(vals) if lower_better else max(vals)) if vals else None
    for c in compare:
        v = c.get("value")
        mark = f" {_ic('check')}" if (v is not None and v == best) else ""
        rows += (f'<tr><td style="text-align:left"><a href="/s/{_esc(c["code"])}">'
                f'{_esc(c["name"])}</a></td>'
                f'<td>{_fmt(v, 2 if unit == "배" else 1)}{unit}{mark}</td>'
                f'<td>{_fmt(c.get("score"))}</td></tr>')
    return (f'<div class="wrap"><table><thead><tr><th style="text-align:left">기업</th>'
            f'<th>{_esc(term["title"].split("(")[0])}</th><th>종합점수</th></tr></thead>'
            f'<tbody>{rows}</tbody></table></div>'
            f'<p class="muted" style="font-size:12px">{_ic("check")} = 이 지표만 보면 '
            f'{"더 낮은" if lower_better else "더 높은"} 쪽이 유리. 데이터는 매 요청 시 '
            f'최신 값으로 자동 갱신됩니다.</p>')


def render_glossary(slug, compare, canonical):
    term = TERMS[slug]
    has_metric = bool(term.get("metric"))
    sections_html = "".join(
        f'<h2>{_esc(h)}</h2><p>{_esc(body)}</p>' for h, body in term["sections"])
    related_html = "".join(
        f'<a href="/learn/{_esc(r)}" class="badge" style="text-decoration:none">'
        f'{_esc(TERMS[r]["title"])}</a> ' for r in term.get("related", []) if r in TERMS)
    names = ", ".join(c["name"] for c in compare) if has_metric else ""
    compare_block = ""
    if has_metric:
        compare_block = (
            f'<h2>{_esc(names)} 비교 <span class="muted" '
            f'style="font-size:13px;font-weight:400">· 실시간 데이터</span></h2>'
            f'{_compare_html(term, compare)}')
    body = f"""
<h1>{_ic(term["emoji"])} {_esc(term["title"])}</h1>
<p class="muted">{_esc(term["lead"])}</p>
{compare_block}
{sections_html}
<h2>함께 보면 좋은 용어</h2>
<p>{related_html or '–'}</p>
<p class="muted footnote" style="margin-top:16px">매매 추천이 아닙니다.
<a href="/learn">← 투자 용어 해설 전체 목록</a> ·
<a href="/">대시보드에서 직접 스크리닝해보기 →</a></p>
"""
    desc = (f"{term['title']} 개념, 계산법, 해석 방법을 {names} 실제 데이터로 알아봅니다." if has_metric
            else f"{term['title']} — 주식 초보자를 위한 기초 개념 설명.")
    return layout(f"{term['title']} | 투자 용어 해설", desc, canonical, body, show_subscribe=False)


